"""
Dataset Audit CLI
=================

Runs the scientific audit (``src/experiments/audit.py``) over every dataset the
tree can reach, writes one JSON per dataset and one Markdown summary table, and
prints the verdicts.

    python audit_datasets.py                       # every reachable dataset
    python audit_datasets.py samld reference_dkdata
    python audit_datasets.py --list
    python audit_datasets.py --out outputs/audits --report docs/datasets.md

A dataset that is not present on this machine is reported as ``not available``
and skipped.  It is never replaced by a substitute and never assumed to look
like the one that is present: the benchmarks are large public downloads and
whether they are here is a fact about this checkout, not about the project.

The Markdown report is regenerated wholesale from the JSON artifacts, so it can
never drift from them.  Prose that belongs to a human - what the finding means,
what to do about it - lives in ``docs/datasets.md``'s surrounding sections and
is preserved by writing the generated table to its own file, which that
document includes by reference.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import traceback
from pathlib import Path
from typing import Any, Callable

from src.experiments.audit import DatasetAudit, audit_dataset, save_audit

DEFAULT_OUTPUT_DIR = Path("outputs/audits")
DEFAULT_REPORT = Path("docs/dataset_audit_table.md")


def _loaders() -> dict[str, tuple[Callable[[], Any], str, list[str]]]:
    """Dataset name -> (zero-argument loader, declared label domain, alias columns).

    The domain is declared here rather than measured, because whether a
    publisher's positive class means "laundering" is a fact about that
    publisher's definition and no statistic on the file can recover it.

    Imported lazily so that ``--list`` works in an environment where one of the
    optional readers is missing.
    """
    from src.experiments import sources
    from src.experiments.audit import DOMAIN_AML, DOMAIN_CARD_FRAUD

    return {
        "reference_dkdata": (
            lambda: sources.load_source("reference_dkdata"),
            DOMAIN_AML,
            [],
        ),
        "samld": (sources.load_samld, DOMAIN_AML, [sources.SAMLD_LABEL_ALIAS]),
        "ibm_aml_sample": (sources.load_ibm_aml_sample, DOMAIN_AML, []),
        "ibm_aml_hi_small": (sources.load_ibm_aml_hi_small, DOMAIN_AML, []),
        "financial_fraud_kaggle": (
            sources.load_financial_fraud,
            DOMAIN_CARD_FRAUD,
            ["fraud_type", "velocity_score", "spending_deviation_score", "geo_anomaly_score"],
        ),
    }


def _row(audit: DatasetAudit) -> str:
    data = audit.data
    labels = audit.labels
    triviality = audit.structural_triviality
    probe = (triviality.get("combined_probe") or {}).get("test_average_precision")
    best = triviality.get("best_single_quantity") or {}
    time_range = data.get("timestamp_range")
    coverage = (
        f"{time_range['min'][:10]} to {time_range['max'][:10]}" if time_range else "none"
    )
    best_ap = best.get("average_precision")
    origin = "synthetic" if audit.spec["synthetic"] else "real"
    forward = "yes" if labels["supports_time_forward_evaluation"] else "no"
    best_cell = "—" if best_ap is None else f"{best_ap:.4f}"
    probe_cell = "—" if probe is None else f"{probe:.4f}"
    return (
        f"| `{audit.name}` "
        f"| {origin} "
        f"| {data['n_entities']:,} "
        f"| {data['n_transactions']:,} "
        f"| {data['n_positive']:,} "
        f"| {data['positive_rate']:.4%} "
        f"| {audit.domain} "
        f"| {coverage} "
        f"| {forward} "
        f"| {best_cell} "
        f"| {probe_cell} "
        f"| **{audit.verdict}** |"
    )


def _render_report(audits: list[DatasetAudit], failures: dict[str, str]) -> str:
    lines = [
        "<!-- GENERATED by audit_datasets.py. Do not edit by hand. -->",
        "",
        "| dataset | origin | entities | transactions | positives | positive rate "
        "| domain | time coverage | time-forward possible | best single quantity AP "
        "| structural probe AP | verdict |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- | --- | --- | ---: | ---: | --- |",
    ]
    lines.extend(_row(a) for a in audits)
    lines.append("")
    lines.append("Reason per dataset:")
    lines.append("")
    for audit in audits:
        lines.append(f"* **`{audit.name}`** — {audit.verdict}. {audit.reason}.")
        lines.append(f"  Recommended use: {audit.recommended_use}.")
        for limitation in audit.limitations:
            lines.append(f"  * {limitation}")
    if failures:
        lines.append("")
        lines.append("Not audited in this run:")
        lines.append("")
        for name, reason in sorted(failures.items()):
            lines.append(f"* `{name}` — {reason}")
    lines.append("")
    return "\n".join(lines)


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("datasets", nargs="*", help="dataset names (default: all)")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--list", action="store_true", help="print dataset names")
    parser.add_argument("--verbose", "-v", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    logging.basicConfig(
        level=logging.INFO if args.verbose else logging.WARNING,
        format="%(levelname)s: %(message)s",
    )

    loaders = _loaders()
    if args.list:
        for name in sorted(loaders):
            print(name)
        return 0

    names = args.datasets or sorted(loaders)
    unknown = [n for n in names if n not in loaders]
    if unknown:
        print(f"error: unknown dataset(s) {unknown}; known: {sorted(loaders)}", file=sys.stderr)
        return 2

    audits: list[DatasetAudit] = []
    failures: dict[str, str] = {}
    for name in names:
        loader, domain, aliases = loaders[name]
        print(f"--- {name}")
        try:
            dataset = loader()
        except FileNotFoundError as exc:
            failures[name] = f"not available on this machine ({exc})"
            print(f"    skipped: {failures[name]}")
            continue
        except Exception as exc:  # noqa: BLE001 - one bad file must not stop the audit
            failures[name] = f"load failed: {type(exc).__name__}: {exc}"
            print(f"    skipped: {failures[name]}")
            if args.verbose:
                traceback.print_exc()
            continue

        audit = audit_dataset(
            dataset, domain=domain, label_alias_columns=aliases, seed=args.seed
        )
        save_audit(audit, args.out)
        audits.append(audit)
        probe = (audit.structural_triviality.get("combined_probe") or {}).get(
            "test_average_precision"
        )
        print(
            f"    {dataset.n_entities:,} entities, {dataset.n_positive:,} positive "
            f"({dataset.prevalence:.4%}); structural probe AP "
            f"{'undefined' if probe is None else f'{probe:.4f}'}"
        )
        print(f"    VERDICT: {audit.verdict} - {audit.reason}")
        del dataset

    if audits:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(_render_report(audits, failures), encoding="utf-8")
        print()
        print(f"audit JSON  : {args.out.resolve()}")
        print(f"audit table : {args.report.resolve()}")
    return 0 if audits else 1


if __name__ == "__main__":
    raise SystemExit(main())
