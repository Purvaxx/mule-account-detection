"""
Final Explainability Module
===========================

Generates human-readable explanation reports for suspicious entities
identified by the inference pipeline.
"""

import pandas as pd


def generate_explanation(row: pd.Series) -> str:
    """Generate a human-readable explanation for a single entity prediction."""
    
    lines = [
        f"ENTITY REPORT: {row['entity_id']}",
        "",
        "MODEL OUTPUT",
        f"Model Risk Score: {row['risk_score']:.4f}",
        f"Model Prediction: {'SUSPICIOUS' if row['predicted_class'] == 1 else 'NORMAL'}",
        "",
        "DISCLAIMER:",
        "The risk score is generated by the trained Graph Neural Network using",
        "the node feature representation and graph topology. The structural",
        "observations below are post-hoc analyst-facing summaries and do not",
        "represent a direct explanation of the model's internal reasoning.",
        "",
        "-" * 50,
        "OBSERVED STRUCTURAL FEATURES",
        "",
        f"Total Incoming: ${row['total_incoming_usd']:,.2f}",
        f"Total Outgoing: ${row['total_outgoing_usd']:,.2f}",
        f"Incoming Transactions: {row['in_degree']}",
        f"Outgoing Transactions: {row['out_degree']}",
        f"Flow Imbalance: {row['flow_imbalance']:+.4f} (-1=all out, +1=all in)",
        "",
        f"Repeated Counterparties (IN): {row['in_repeated_ratio']:.4f}",
        f"Repeated Counterparties (OUT): {row['out_repeated_ratio']:.4f}",
        f"Maximum Parallel Transactions: {row['max_parallel_edge']}",
        f"Mean Parallel Transactions: {row['mean_parallel_edge']:.4f}",
        f"Reciprocal Counterparties (IN): {row['reciprocal_in']}",
        f"Reciprocal Counterparties (OUT): {row['reciprocal_out']}",
        "",
        "-" * 50,
        "HEURISTIC STRUCTURAL FLAGS",
        "",
    ]
    
    flags = []
    
    if row['reciprocal_out'] > 0 or row['reciprocal_in'] > 0:
        val = max(row['reciprocal_in'], row['reciprocal_out'])
        flags.append(f"Entity exhibits reciprocal (two-way) transaction flows with {val} counterparty(ies).")
        
    out_thresh = 2.0
    if row['out_repeated_ratio'] > out_thresh:
        flags.append(
            f"Outgoing repetition ratio exceeds configured threshold "
            f"({row['out_repeated_ratio']:.2f} > {out_thresh})."
        )
        
    in_thresh = 2.0
    if row['in_repeated_ratio'] > in_thresh:
        flags.append(
            f"Incoming repetition ratio exceeds configured threshold "
            f"({row['in_repeated_ratio']:.2f} > {in_thresh})."
        )
        
    parallel_thresh = 5
    if row['max_parallel_edge'] > parallel_thresh:
        flags.append(
            f"Maximum parallel-edge count exceeds configured threshold "
            f"({row['max_parallel_edge']} > {parallel_thresh})."
        )
        
    imbalance_thresh = 0.1
    if abs(row['flow_imbalance']) < imbalance_thresh and (row['in_degree'] > 0 and row['out_degree'] > 0):
        flags.append(
            f"Inflow/outflow volumes are closely balanced "
            f"(abs({row['flow_imbalance']:.4f}) < {imbalance_thresh})."
        )

    if not flags:
        flags.append("No heuristic structural thresholds exceeded.")

    for flag in flags:
        lines.append(f"* {flag}")
        
    lines.append("=" * 50)
    
    return "\n".join(lines)


def explain_suspicious_entities(results_df: pd.DataFrame, top_k: int = 10) -> str:
    """Generate explanations for the top suspicious entities."""
    suspicious = results_df[results_df['predicted_class'] == 1]
    
    if len(suspicious) == 0:
        suspicious = results_df.head(top_k)
    else:
        suspicious = suspicious.head(top_k)
        
    reports = []
    for _, row in suspicious.iterrows():
        reports.append(generate_explanation(row))
        
    return "\n\n".join(reports)
