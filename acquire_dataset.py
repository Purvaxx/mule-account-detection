@dataclass
class AcquisitionManifest:
    """What was actually obtained."""

    name: str
    filename: str
    url: str
    resolved_host: Optional[str]
    acquired_at: str
    bytes: int
    sha256: str
    publisher: str
    licence: str
    citation: str
    landing_page: str
    header_line: Optional[str] = None
    n_lines_sampled: Optional[int] = None
    notes: list[str] = field(default_factory=list)
    tool: str = "acquire_dataset.py"

    def to_dict(self) -> dict:
        return asdict(self)


def _sha256(path: Path, chunk: int = 1 << 22) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(chunk), b""):
            digest.update(block)
    return digest.hexdigest()


def _header_line(path: Path) -> Optional[str]:
    try:
        with path.open("r", encoding="utf-8", errors="replace") as fh:
            return fh.readline().rstrip("\n\r") or None
    except OSError:
        return None


def _curl(url: str, target: Path, timeout: int) -> str:
    """Download ``url`` to ``target``, returning the host the bytes came from.

    ``curl`` is used rather than a Python HTTP client because it resumes a
    partial transfer (``-C -``), which matters for a half-gigabyte file on a
    connection that may drop. The effective URL is captured so the manifest
    records where the bytes actually came from, not just what was asked for.
    """
    if shutil.which("curl") is None:
        raise RuntimeError(
            "curl is not available; download the file manually - see the "
            "manual step printed by --verify-only"
        )
    partial = target.with_suffix(target.suffix + ".part")
    result = subprocess.run(
        [
            "curl", "-sS", "-L", "-C", "-",
            "--max-time", str(timeout),
            "--retry", "3", "--retry-delay", "5",
            "-w", "%{url_effective}",
            "-o", str(partial),
            url,
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"curl failed (exit {result.returncode}): {result.stderr.strip()}"
        )
    partial.replace(target)
    effective = (result.stdout or "").strip()
    return effective.split("/")[2] if "//" in effective else None


def acquire(
    dataset: RemoteDataset,
    dest_dir: Path,
    *,
    timeout: int = 1800,
    verify_only: bool = False,
) -> AcquisitionManifest:
    """Fetch ``dataset`` into ``dest_dir`` (or just verify what is there)."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    target = dest_dir / dataset.filename
    resolved_host: Optional[str] = None

    if target.exists():
        print(f"    already present: {target} ({target.stat().st_size:,} bytes)")
    elif verify_only:
        raise FileNotFoundError(
            f"{target} is not present and --verify-only was given"
        )
    else:
        print(f"    downloading {dataset.url}")
        resolved_host = _curl(dataset.url, target, timeout)

    size = target.stat().st_size
    if dataset.expected_bytes is not None and size != dataset.expected_bytes:
        print(
            f"    WARNING: {size:,} bytes, publisher listing said "
            f"{dataset.expected_bytes:,}. The file may have been revised; the "
            f"manifest records what is on disk."
        )

    print("    hashing...")
    manifest = AcquisitionManifest(
        name=dataset.name,
        filename=dataset.filename,
        url=dataset.url,
        resolved_host=resolved_host,
        acquired_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        bytes=size,
        sha256=_sha256(target),
        publisher=dataset.publisher,
        licence=dataset.licence,
        citation=dataset.citation,
        landing_page=dataset.landing_page,
        header_line=_header_line(target),
        notes=list(dataset.notes),
    )
    return manifest


def save_manifest(manifest: AcquisitionManifest, directory: Path = MANIFEST_DIR) -> Path:
    """Write the manifest, refusing to overwrite a differing digest silently."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{manifest.name}.json"
    if path.exists():
        existing = json.loads(path.read_text(encoding="utf-8"))
        if existing.get("sha256") != manifest.sha256:
            raise RuntimeError(
                f"{path} records sha256 {existing.get('sha256')} but the file "
                f"on disk hashes to {manifest.sha256}. These are different "
                f"files. Results computed from one are not results for the "
                f"other; resolve this deliberately rather than by overwriting."
            )
    path.write_text(json.dumps(manifest.to_dict(), indent=2) + "\n", encoding="utf-8")
    return path


def _manual_instructions(dataset: RemoteDataset, dest_dir: Path) -> str:
    return "\n".join(
        [
            f"Manual acquisition for '{dataset.name}':",
            f"  1. Open {dataset.landing_page}",
            f"  2. Sign in to Kaggle and accept the licence "
            f"({dataset.licence}).",
            f"  3. Download '{dataset.filename}'.",
            f"  4. Place it at: {dest_dir / dataset.filename}",
            f"  5. Run: python acquire_dataset.py {dataset.name} --verify-only",
            "     which hashes the file and writes the provenance manifest.",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("datasets", nargs="*", help="registry names (default: none)")
    parser.add_argument("--dest", type=Path, default=DEFAULT_DEST)
    parser.add_argument("--manifests", type=Path, default=MANIFEST_DIR)
    parser.add_argument("--timeout", type=int, default=1800)
    parser.add_argument(
        "--verify-only",
        action="store_true",
        help="do not download; hash what is already on disk and write the manifest",
    )
    parser.add_argument("--list", action="store_true")
    args = parser.parse_args(argv)

    if args.list or not args.datasets:
        print("Acquirable benchmarks (none are committed to this repository):\n")
        for name, dataset in sorted(REGISTRY.items()):
            print(f"  {name}")
            print(f"      file    : {dataset.filename}")
            print(f"      licence : {dataset.licence}")
            print(f"      source  : {dataset.landing_page}")
        print(f"\nDefault destination: {args.dest}")
        return 0 if args.list else 2

    unknown = [n for n in args.datasets if n not in REGISTRY]
    if unknown:
        print(f"error: unknown dataset(s) {unknown}; known: {sorted(REGISTRY)}",
              file=sys.stderr)
        return 2

    failures = 0
    for name in args.datasets:
        dataset = REGISTRY[name]
        print(f"--- {name}")
        try:
            manifest = acquire(
                dataset, args.dest, timeout=args.timeout, verify_only=args.verify_only
            )
        except Exception as exc:  # noqa: BLE001 - the failure is the result
            failures += 1
            print(f"    FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
            print(file=sys.stderr)
            print(_manual_instructions(dataset, args.dest), file=sys.stderr)
            continue
        path = save_manifest(manifest, args.manifests)
        print(f"    {manifest.bytes:,} bytes  sha256 {manifest.sha256[:16]}...")
        print(f"    manifest: {path}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
