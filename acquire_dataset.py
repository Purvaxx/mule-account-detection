"""
External Benchmark Acquisition CLI
==================================

Downloads a published benchmark this repository does not vendor, and writes a
manifest recording exactly what was obtained.

    python acquire_dataset.py --list
    python acquire_dataset.py ibm_aml_hi_small
    python acquire_dataset.py ibm_aml_hi_small --dest "/path/to/data"
    python acquire_dataset.py ibm_aml_hi_small --verify-only

Why this exists
---------------
The benchmarks are hundreds of megabytes to gigabytes and are **not committed**
(the repository has never vendored one). What *is*
committed is this script and the manifest it writes, so anyone can later
reproduce the acquisition rather than inherit a file of unknown origin.

What a manifest records
-----------------------
Source name, the exact URL requested, the resolved host the bytes came from,
acquisition timestamp, byte count, SHA-256, the publisher's licence, and the
header line of the file. That is enough for a later reader to establish that
the file they hold is the file the results were computed from - which is the
only claim a manifest can honestly support.

Integrity
---------
The digest is computed **after** the download from the bytes on disk. It is a
record of what arrived, not a check against a publisher-supplied checksum,
because Kaggle does not publish per-file checksums for this dataset. A manifest
that already exists is compared against, and a mismatch is reported as an error
rather than silently overwritten.

Nothing here fabricates data. If a download fails, the failure is the result.
"""

