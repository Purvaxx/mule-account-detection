#: Utility prefixes that can carry a palette token in these templates.
_SYSTEM_CLASS = re.compile(r"system-([a-z][a-z-]*)")

#: ``system-ui`` is a font stack, not a palette token.
_NOT_A_COLOUR = {"ui"}

_COLOUR_CONSUMERS = _TEMPLATES + _SCRIPTS


def _declared_system_colours():
    """The palette keys the page's Tailwind config actually declares."""
    page = _read("src/ui/pages/index.html")
    return set(re.findall(r"'?([a-z][a-z-]*)'?:\s*amlColor\(", page))


@pytest.mark.parametrize("source", _COLOUR_CONSUMERS)
def test_every_system_colour_class_is_declared(source):
    """A colour class Tailwind does not know about renders as nothing.

    ``text-system-danger`` is not a compile error and not a runtime error: it
    is simply an unstyled element, which is exactly the kind of defect a dark
    console hides.  Every ``system-*`` class used anywhere — templates and the
    class strings ``app.js`` returns — must resolve to a declared token.
    """
    declared = _declared_system_colours()
    used = {name for name in _SYSTEM_CLASS.findall(_read(source))}
    used -= _NOT_A_COLOUR
    undeclared = sorted(used - declared)
    assert not undeclared, (
        f"{source} uses colour classes the Tailwind config does not declare: "
        f"{undeclared}. Add the token in theme.py and map it in the page's "
        f"tailwind.config, or fix the typo."
    )


def test_components_are_served_uncacheable():
    """The console is composed from the working tree on every request.

    ``app.js`` and the fragments are served by the static fallback, which sets
    only ``Last-Modified``.  A browser may treat that as heuristically fresh
    and keep running a stale component against freshly composed HTML — the two
    then disagree about which state fields exist and bindings fail at runtime.
    """
    from src.ui.app import APIHandler
    from socketserver import TCPServer
    import threading
    import requests
    import time

    server = TCPServer(("127.0.0.1", 0), APIHandler)
    port = server.server_address[1]
    thread = threading.Thread(target=server.serve_forever)
    thread.daemon = True
    thread.start()
    try:
        time.sleep(0.1)
        response = requests.get(f"http://127.0.0.1:{port}/src/ui/components/app.js")
        assert response.status_code == 200
        assert response.headers.get("Cache-Control") == "no-store"
        served = response.text.replace(chr(13) + chr(10), chr(10))
        assert served == _read("src/ui/components/app.js")
    finally:
        server.shutdown()
        server.server_close()


