def test_ui_help_endpoint():
    """Verify the /api/help endpoint returns valid help configuration."""
    from src.ui.app import APIHandler
    from http.server import HTTPServer
    from socketserver import TCPServer
    import threading
    import requests
    import time

    server = TCPServer(("127.0.0.1", 0), APIHandler)
    port = server.server_address[1]

    thread = threading.Thread(target=server.serve_forever)
    thread.daemon = True
    thread.start()

    try:
        time.sleep(0.1)
        response = requests.get(f"http://127.0.0.1:{port}/api/help")
        assert response.status_code == 200

        raw_text = response.text
        assert raw_text.strip().endswith("}"), "Response body does not end cleanly with JSON."
        assert "<html" not in raw_text.lower(), "Response body contains HTML unexpectedly."

        import json
        data = json.loads(raw_text)
        assert "global_guide" in data
        assert "risk_score" in data
        assert "prediction" in data

        # Check that forbidden claims are NOT in the data
        text_content = json.dumps(data).lower()
        forbidden = ["hackathon", "competition", "judges", "demo", "prototype", "submission", "event"]
        for f in forbidden:
            assert f not in text_content, f"Forbidden term '{f}' found in help content."
    finally:
        server.shutdown()
        server.server_close()


