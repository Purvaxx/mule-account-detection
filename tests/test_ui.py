def test_ui_network_visualization_filtering():
    """Verify visualization projection rules for dense graphs."""
    adapter = DetectionAdapter()
    from src.ui.resolver import WorkspaceAnalysisResolver
    resolver = WorkspaceAnalysisResolver()
    context = resolver.get_analysis_context(None)

    # HILUX SERVICES LP is known to be a dense entity
    entity_id = "HILUX SERVICES LP"
    if entity_id not in context.graph:
        pytest.skip(f"{entity_id} not in graph")

    # Full authoritative graph check before
    nodes_before = context.graph.number_of_nodes()
    edges_before = context.graph.number_of_edges()
    assert nodes_before == 3440
    assert edges_before == 16940

    # Test Default: max_neighbors=15
    net_default = adapter.get_network(entity_id, context, max_neighbors=15, min_tx=1)
    assert len(net_default["nodes"]) <= 16  # 15 neighbors + 1 target
    assert net_default["hidden_count"] > 0

    # Test Limits
    net_5 = adapter.get_network(entity_id, context, max_neighbors=5, min_tx=1)
    assert len(net_5["nodes"]) <= 6
    assert net_5["hidden_count"] > net_default["hidden_count"]

    # Test All
    net_all = adapter.get_network(entity_id, context, max_neighbors=0, min_tx=1)
    assert len(net_all["nodes"]) > 16
    assert net_all["hidden_count"] == 0

    # Test Min Tx
    net_high_tx = adapter.get_network(entity_id, context, max_neighbors=0, min_tx=10)
    assert len(net_high_tx["nodes"]) < len(net_all["nodes"])

    # Test Reciprocal
    net_recip = adapter.get_network(entity_id, context, max_neighbors=0, min_tx=1, reciprocal_only=True)
    assert len(net_recip["nodes"]) <= len(net_all["nodes"])

    # Full authoritative graph check after
    assert context.graph.number_of_nodes() == nodes_before
    assert context.graph.number_of_edges() == edges_before

