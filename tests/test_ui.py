#: A literal colour anywhere outside theme.py.
_HEX = "#" + "[0-9A-Fa-f]{3,8}" + chr(92) + "b"


def _read(relative_path):
    path = os.path.join(os.path.dirname(__file__), "..", relative_path)
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


